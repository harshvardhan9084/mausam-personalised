let currentLang = null;

export function getLang() {
  if (currentLang) return currentLang;
  currentLang = store.lang.get() === 'hi' ? 'hi' : 'en';
  return currentLang;
}

export function setLang(l) {
  currentLang = l === 'hi' ? 'hi' : 'en';
  store.lang.set(currentLang);
  document.documentElement.lang = currentLang === 'hi' ? 'hi' : 'en';
}

/** Translate a key with {var} interpolation. Falls back to English, then the key itself. */
export function t(key, vars = null) {
  const entry = dict[key];
  if (!entry) return key;
  const lang = getLang();
  let s = (lang === 'hi' && entry[1]) ? entry[1] : entry[0];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Locale-aware date helpers honouring the current language. */
export function dateLocale() { return getLang() === 'hi' ? 'hi-IN' : undefined; }
export function todayLabel() { return t('today'); }
export function tomorrowLabel() { return t('tomorrow'); }
